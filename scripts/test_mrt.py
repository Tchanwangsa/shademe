def _svp_log1p(ta):
    """pythermalcomfort 3.3.0's variant of the Hardy es(): log1p(T) where the
    official UTCI code, Hardy 1998 and ECMWF thermofeel all use log(T)."""
    tk = np.asarray(ta, float) + M.T0
    g = (-2.8365744e3, -6.028076559e3, 1.954263612e1, -2.737830188e-2,
         1.6261698e-5, 7.0229056e-10, -1.8680009e-13)
    es = 2.7150305 * np.log1p(tk)
    for i, gi in enumerate(g):
        es = es + gi * tk ** (i - 2)
    return np.exp(es) * 0.01


def utci_table(rows, title):
    rule(title)
    ta, tr, va, rh, exp = (np.array([r[i] for r in rows], float) for i in range(5))
    got, _ = M.utci(ta, tr, va, rh=rh)                       # ours: Hardy log(T)
    alt, _ = M.utci(ta, tr, va, vp_hpa=_svp_log1p(ta) * rh / 100.0)   # their log1p
    print("    Ta   Tmrt    va   RH | expected |    ours     diff | log1p-variant  rounds to")
    for i in range(len(rows)):
        print("  %5.1f %6.1f %5.1f %5.0f | %8.1f | %7.3f %+8.3f | %13.3f %10.1f"
              % (ta[i], tr[i], va[i], rh[i], exp[i], got[i], got[i] - exp[i],
                 alt[i], round(float(alt[i]), 1)))
    d = np.abs(got - exp)
    dalt = np.abs(np.round(alt, 1) - exp)
    print("  ours (Hardy log T)  max |diff| = %.4f degC" % d.max())
    print("  log1p variant, rounded to 0.1 as the references are: max |diff| = %.4f" % dalt.max())
    # THE coefficient test: the references were generated by pythermalcomfort, so
    # running its exact vapour-pressure formula must reproduce them bit-for-bit
    # after the 0.1 rounding they are quoted at. If a single coefficient were wrong
    # this would fail; it isolates the coefficients from the humidity conversion.
    check(title + " -- coefficients (log1p variant reproduces refs exactly)",
          dalt.max() == 0.0, "max %.4f" % dalt.max())
    check(title + " -- ours within 0.1 of published", d.max() < 0.1, "max %.4f" % d.max())
    return d.max()


