rule("(a1) which saturation vapour pressure formula is right?")
print("  Our residual against both reference sets is ~0.02-0.08 degC and one-sided.")
print("  It is NOT a coefficient error -- it is the es() formula. Measured against")
print("  published saturation vapour pressure over water (WMO/CRC), hPa:")
print("     Ta |  true e_s |  log(T) ours |  log1p(T) pythermalcomfort")
TRUE_ES = [(0, 6.112), (10, 12.28), (20, 23.39), (25, 31.69), (30, 42.46),
           (35, 56.26), (40, 73.85)]
err_ours = err_them = 0.0
for t, v in TRUE_ES:
    a, b = float(M.svp_hpa(t)), float(_svp_log1p(t))
    err_ours = max(err_ours, abs(a - v) / v)
    err_them = max(err_them, abs(b - v) / v)
    print("  %5d | %9.3f | %12.3f | %25.3f" % (t, v, a, b))
print("  max relative error:  ours %.2e   pythermalcomfort %.2e" % (err_ours, err_them))
check("our svp_hpa matches true saturation vapour pressure to <0.1%", err_ours < 1e-3,
      "%.2e" % err_ours)
print("  -> pythermalcomfort 3.3.0's log1p is an upstream bug (~0.9%% high in e_s,")
print("     ~0.03 degC in UTCI). We keep log(T). Worth reporting upstream.")

