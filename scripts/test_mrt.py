print("  local dUTCI/dva over Ta<=35: %.2f%% of steps are POSITIVE, steepest %+.3f degC/(m/s)."
      % (100.0 * (dv > 0).mean(), dv.max()))
print("  The Brode polynomial genuinely wiggles in va above Ta ~28 (it is a 6th-order")
print("  least-squares fit, not a monotone model), and above Ta ~37 the net sign")
