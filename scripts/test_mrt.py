# ---------------------------------------------------------------- (d) quadrant
rule("(d) THE QUADRANT TEST -- sun helps when cold, hurts when hot")
print("  One code path, no branches: mrt() then utci() then stress().")
print("  Sunny  = svf 0.95, shade 0.00.   Shaded = svf 0.30, shade 1.00 (tree canopy).")
DAYS = [("cold day  8C", dict(ta=8.0, rh=70.0, va=2.0, i_dir_h=430.0, i_dif=90.0,
                              elev_deg=32.0, ts_sun=16.0, ts_shade=8.0)),
        ("hot day  36C", dict(ta=36.0, rh=25.0, va=2.0, i_dir_h=846.0, i_dif=110.0,
                              elev_deg=70.0, ts_sun=58.0, ts_shade=38.0))]
EXP = [("sunny", 0.95, 0.0, "ts_sun"), ("shaded", 0.30, 1.0, "ts_shade")]
print("\n  %-12s %-7s %7s %7s %7s %8s   %s" %
      ("day", "expo", "Ta", "MRT", "UTCI", "stress", "category"))
res = {}
for dname, p in DAYS:
    for ename, svf, sh, tskey in EXP:
        tm = M.mrt(p["ta"], svf, sh, p["i_dir_h"], p["i_dif"], p["elev_deg"],
                   p[tskey], rh=p["rh"])
        u, _ = M.utci(p["ta"], tm, p["va"], rh=p["rh"])
        st = M.stress(u)
        res[(dname, ename)] = float(st)
        print("  %-12s %-7s %7.1f %7.1f %7.1f %8.2f   %s"
              % (dname, ename, p["ta"], tm, u, st, M.category(u)))
d_cold = res[("cold day  8C", "sunny")] - res[("cold day  8C", "shaded")]
d_hot = res[("hot day  36C", "sunny")] - res[("hot day  36C", "shaded")]
print("\n  delta stress (sunny - shaded):  cold day %+.2f   hot day %+.2f" % (d_cold, d_hot))
check("sun REDUCES stress on the cold day", d_cold < 0, "%+.2f" % d_cold)
check("sun INCREASES stress on the hot day", d_hot > 0, "%+.2f" % d_hot)
print("  -> the sign flip comes from the physics, not from an if-statement.")

